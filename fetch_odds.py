def normalize_name(name):
    name = name.strip()
    return NAME_MAP.get(name, name)


def fmt_odds(price):
    """Convert integer to American odds string."""
    try:
        n = int(price)
        return f"+{n}" if n >= 0 else str(n)
    except Exception:
        return None


def load_existing():
    """Load existing odds.json as a base."""
    try:
        with open(OUTPUT_FILE) as f:
            data = json.load(f)
        return data.get("odds", {})
    except Exception:
        return {}


def save_odds(odds_dict, source):
    data = {
        "odds": odds_dict,
        "exportedAt": datetime.datetime.utcnow().isoformat() + "Z",
        "source": source,
        "note": "Generated by fetch_odds.py — push to GitHub root.",
    }
    with open(OUTPUT_FILE, "w") as f:
        json.dump(data, f, indent=2)
    print(f"✓ Saved {len(odds_dict)} players to {OUTPUT_FILE}")
    print(f"  Source: {source}")


# ── Text parser ───────────────────────────────────────────────────────────────
def parse_odds_from_text(text):
    """
    Parse player odds from free-text pages.
    Handles patterns like:
      "Scottie Scheffler +700"
      "Rory McIlroy +850"
      "Scottie Scheffler     +700"
    """
    odds = {}
    # Each name word: leading capital, then letters/periods/apostrophes/hyphens —
    # this allows Mc/Mac names (McIlroy, MacIntyre), initials (J.T., J.J.), and
    # accented characters (Åberg, Højgaard, Välimäki), not just all-lowercase tails.
    pattern = re.compile(
        r'([A-Z\u00C0-\u024F][A-Za-z\u00C0-\u024F\'.-]*'
        r'(?:[ \t]+[A-Z\u00C0-\u024F][A-Za-z\u00C0-\u024F\'.-]*){1,3})'
        r'[ \t]{0,10}([+-]\d{3,6})\b'
    )
    for match in pattern.finditer(text):
        name = normalize_name(match.group(1).strip())
        price_str = match.group(2)
        if len(name) < 8:
            continue
        try:
            val = int(price_str)
            if abs(val) < 100:
                continue  # odds are always >=100, this filters out golf scores like -8/+3
        except Exception:
            continue
        formatted = fmt_odds(val)
        if formatted:
            if name not in odds or abs(val) < abs(int(odds[name])):
                odds[name] = formatted
    return odds


def scrape_url(url, min_players=10):
    r = requests.get(url, headers=HEADERS, timeout=15)
    if r.status_code != 200:
        print(f"    HTTP {r.status_code}")
        return None
    soup = BeautifulSoup(r.text, "html.parser")
    text = soup.get_text(" ", strip=True)
    odds = parse_odds_from_text(text)
    if len(odds) >= min_players:
        return odds
    print(f"    Only parsed {len(odds)} players, need >= {min_players} — skipping")
    return None


