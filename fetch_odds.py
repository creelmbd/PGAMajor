# ── Text parser ───────────────────────────────────────────────────────────────
def parse_odds_from_text(text):
    """
    Parse player odds from free-text pages.
    Handles patterns like:
      "Scottie Scheffler +480"
      "Rory McIlroy +850"
      "Scottie Scheffler     +480"
    """
    odds = {}
    # Pattern: First Last +NNNN or First Last -NNN
    pattern = re.compile(
        r'([A-Z][a-záàäâéèëêíìïîóòöôúùüûýñãõæøåčšž\u00C0-\u024F]+'
        r'(?:\s+[A-Z][a-záàäâéèëêíìïîóòöôúùüûýñãõæøåčšž\u00C0-\u024F]+)+)'
        r'\s{0,10}([+-]\d{3,6})\b'
    )
    for match in pattern.finditer(text):
        name = normalize_name(match.group(1).strip())
        price_str = match.group(2)
        # Skip obviously wrong matches (short names, scores, etc.)
        if len(name) < 8:
            continue
        # Skip if it looks like a score (e.g. -8, +3) rather than odds
        try:
            val = int(price_str)
            if abs(val) < 100:
                continue  # odds are always >=100
        except:
            continue
        formatted = fmt_odds(val)
        if formatted:
            # Keep best (lowest) odds if duplicate
            if name not in odds or abs(val) < abs(int(odds[name])):
                odds[name] = formatted
    return odds

