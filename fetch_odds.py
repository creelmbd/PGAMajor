def normalize_name(name):
    name = name.strip()
    return NAME_MAP.get(name, name)

def fmt_odds(price):
    """Convert integer to American odds string."""
    try:
        n = int(price)
        return f"+{n}" if n >= 0 else str(n)
    except:
        return None

def load_existing():
    """Load existing odds.json as a base."""
    try:
        with open(OUTPUT_FILE) as f:
            data = json.load(f)
        return data.get("odds", {})
    except:
        return {}

def save_odds(odds_dict, source):
    data = {
        "odds": odds_dict,
        "exportedAt": datetime.datetime.utcnow().isoformat() + "Z",
        "source": source,
        "note": "Generated by fetch_odds.py — push to GitHub root."
    }
    with open(OUTPUT_FILE, "w") as f:
        json.dump(data, f, indent=2)
    print(f"✓ Saved {len(odds_dict)} players to {OUTPUT_FILE}")
    print(f"  Source: {source}")

# ── Source 1: The Odds API ────────────────────────────────────────────────────
def try_odds_api():
    # Check for API key in env var or file
    api_key = os.environ.get("ODDS_API_KEY", "")
    if not api_key:
        key_file = Path(__file__).parent / "odds_api_key.txt"
        if key_file.exists():
            api_key = key_file.read_text().strip()
    if not api_key:
        print("  Skipping The Odds API — no key found (set ODDS_API_KEY env var or create odds_api_key.txt)")
        return None

    print("  Trying The Odds API...")
    try:
        r = requests.get(
            "https://api.the-odds-api.com/v4/sports/golf_pga_championship_winner/odds",
            params={"regions": "us", "markets": "outrights", "oddsFormat": "american", "apiKey": api_key},
            headers=HEADERS, timeout=15
        )
        remaining = r.headers.get("x-requests-remaining", "?")
        print(f"  Requests remaining: {remaining}")
        if r.status_code == 404:
            print("  Market not active (tournament may be live — futures closed)")
            return None
        r.raise_for_status()
        data = r.json()
        odds = {}
        for book in data:
            for market in book.get("markets", []):
                for outcome in market.get("outcomes", []):
                    name = normalize_name(outcome["name"])
                    price = outcome["price"]
                    formatted = fmt_odds(price)
                    if formatted and (name not in odds or abs(price) < abs(int(odds[name]))):
                        odds[name] = formatted
        if odds:
            print(f"  ✓ Got {len(odds)} players from The Odds API")
            return odds, "The Odds API"
        print("  No odds returned")
        return None
    except Exception as e:
        print(f"  The Odds API failed: {e}")
        return None

