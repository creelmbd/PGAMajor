# ── Main ──────────────────────────────────────────────────────────────────────
def main():
    print("=" * 50)
    print("2026 Open Championship Odds Fetcher")
    print("=" * 50)

    existing = load_existing()
    print(f"Existing odds.json: {len(existing)} players\n")

    result = None
    for source_fn in [try_cbssports_primary, try_cbssports_secondary, try_bleacherreport]:
        result = source_fn()
        if result:
            break
        print()

    if result:
        new_odds, source_name = result
        # Merge: new data wins, keep existing for any players not found
        merged = {**existing, **new_odds}
        save_odds(merged, source_name)
        print("\nTop 10 odds:")
        sorted_odds = sorted(merged.items(), key=lambda x: int(x[1].replace("+", "")))
        for name, odds in sorted_odds[:10]:
            print(f"  {name:<30} {odds}")
    else:
        print("\n⚠ All sources failed. Keeping existing odds.json unchanged.")
        print("  You can manually update odds.json with the current lines.")
        if not existing:
            print("  No existing odds found — creating with seed data.")
            save_odds(SEED_ODDS, "Manual seed")


if __name__ == "__main__":
    main()